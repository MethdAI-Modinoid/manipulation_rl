import xml.etree.ElementTree as ET
from pathlib import Path

import mujoco

REPO = Path(__file__).resolve().parents[2]
ROBOT = REPO / "robot"
SRC = ROBOT / "g1_revo2.xml"
OUT = ROBOT / "g1_revo2_rl.xml"

COUPLINGS = [
    ("right_thumb_distal_joint",  "right_thumb_proximal_joint",  "0 1.0 0 0 0"),
    ("right_index_distal_joint",  "right_index_proximal_joint",  "0 1.156 0 0 0"),
    ("right_middle_distal_joint", "right_middle_proximal_joint", "0 1.156 0 0 0"),
    ("right_ring_distal_joint",   "right_ring_proximal_joint",   "0 1.156 0 0 0"),
    ("right_pinky_distal_joint",  "right_pinky_proximal_joint",  "0 1.156 0 0 0"),
]

def keep_joint(name: str) -> bool:
    if name is None or not name.startswith("right_"):
        return False
    return not any(seg in name for seg in ("hip", "knee", "ankle"))

def find_body(root, name):
    for b in root.iter("body"):
        if b.get("name") == name:
            return b
    return None

def main():
    tree = ET.parse(SRC)
    root = tree.getroot()
    root.set("model", "g1_revo2_rl")
    kept, welded = [], []
    for body in root.iter("body"):
        for child in list(body):
            if child.tag in ("joint", "freejoint"):
                jname = child.get("name")
                if keep_joint(jname):
                    kept.append(jname)
                else:
                    body.remove(child)
                    welded.append(jname)

    def is_grasp_body(name):
        return bool(name) and name.startswith("right_") and any(
            k in name for k in ("hand_mount", "thumb", "index", "middle", "ring", "pinky")
        )
    n_off = 0
    for body in root.iter("body"):
        if is_grasp_body(body.get("name")):
            continue
        for g in body.findall("geom"):
            g.set("contype", "0")
            g.set("conaffinity", "0")
            n_off += 1
    print(f"disabled collision on {n_off} non-hand geoms (only right hand + cube + table collide)")

    pelvis = find_body(root, "pelvis")
    assert pelvis is not None, "no pelvis body found"
    pelvis.set("pos", "0 0 0.774")   
    pelvis.set("quat", "1 0 0 0")

    import numpy as np
    mount = find_body(root, "right_hand_mount")
    assert mount is not None, "no right_hand_mount body found"
    q = np.array([float(x) for x in mount.get("quat").split()])
    LOCZ_NEG90 = np.array([0.70710678, 0.0, 0.0, -0.70710678])  # -90° about local Z
    qn = np.zeros(4)
    mujoco.mju_mulQuat(qn, q, LOCZ_NEG90)
    qn = qn / np.linalg.norm(qn)
    mount.set("quat", " ".join(f"{v:.6f}" for v in qn))
    print(f"corrected right_hand_mount quat {q.round(4).tolist()} -> {qn.round(4).tolist()} (Ry+90 convention)")

    FINGERS = ("thumb", "index", "middle", "ring", "pinky")
    n_tip = 0
    for f in FINGERS:
        b = find_body(root, f"right_{f}_distal_link")
        if b is None:
            continue
        for i, g in enumerate(b.findall("geom")):
            if g.get("contype") == "0":  # visual-only
                continue
            g.set("name", f"right_{f}_distal_col{i}")
            g.set("priority", "1")
            g.set("condim", "3")
            g.set("friction", "3.0 0.01 0.001")
            n_tip += 1
    print(f"tagged {n_tip} fingertip collision geoms (priority=1, condim=3, friction=3, stiff contact)")

    n_gc = 0
    for b in root.iter("body"):
        name = b.get("name") or ""
        if name.startswith("right_") and not any(s in name for s in ("hip", "knee", "ankle")):
            b.set("gravcomp", "1")
            n_gc += 1
    print(f"gravity comp on {n_gc} right arm/hand bodies")

    # ── 3. Add the right hand's finger couplings ──
    equality = ET.SubElement(root, "equality")
    for j1, j2, poly in COUPLINGS:
        ET.SubElement(equality, "joint", {
            "joint1": j1, "joint2": j2, "polycoef": poly,
            "solref": "0.004 1", "solimp": "0.99 0.999 0.001",
        })

    # ── 4. Write ──
    ET.indent(tree, space="  ")
    header = ("<!-- GENERATED by rl/simtoolreal_g1/build_rl_model.py - do not edit by hand.\n"
              "     Fixed-base G1: only the right arm + right hand articulate; the lower\n"
              "     body, torso, and left arm/hand are welded rigid. -->\n")
    with open(OUT, "w") as f:
        f.write(header)
        f.write(ET.tostring(root, encoding="unicode"))
        f.write("\n")
    print(f"wrote {OUT}  (kept {len(kept)} joints, welded {len(welded)})")
    print(f"  kept: {kept}")

    # ── 5. Validate ──
    m = mujoco.MjModel.from_xml_path(str(OUT))
    print(f"compiles: nbody={m.nbody} njnt={m.njnt} neq={m.neq}")
    assert m.njnt == 18, f"expected 18 joints (right arm 7 + right hand 11), got {m.njnt}"
    assert m.neq == 5, f"expected 5 right-hand couplings, got {m.neq}"
    print("OK: 18 joints, 5 couplings — only right arm + right hand move")


if __name__ == "__main__":
    main()
